"""Training and checkpoint utilities for the from-scratch language model."""

from __future__ import annotations

import hashlib
import json
import math
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Any

import torch
from torch import Tensor

from .bpe_tokenizer import BPETokenizer
from .model import TinyTransformerLM, TransformerConfig
from .tokenizer import CharacterTokenizer


@dataclass(frozen=True)
class LanguageModelTrainingConfig:
    """Configuration for a reproducible language-model training run."""

    block_size: int = 128
    n_layers: int = 4
    n_heads: int = 4
    n_embd: int = 128
    dropout: float = 0.1
    batch_size: int = 16
    max_steps: int = 1000
    learning_rate: float = 3e-4
    weight_decay: float = 0.01
    eval_interval: int = 100
    eval_batches: int = 10
    train_fraction: float = 0.9
    grad_clip: float = 1.0
    seed: int = 42
    tokenizer_type: str = "character"
    tokenizer_vocab_size: int = 512
    tokenizer_min_frequency: int = 2
    device: str = "auto"

    def __post_init__(self) -> None:
        if self.block_size < 2:
            raise ValueError("block_size must be at least 2.")
        if self.n_layers < 1 or self.n_heads < 1 or self.n_embd < 1:
            raise ValueError("Model dimensions must be positive.")
        if self.n_embd % self.n_heads:
            raise ValueError("n_embd must be divisible by n_heads.")
        if not 0.0 <= self.dropout < 1.0:
            raise ValueError("dropout must be in [0, 1).")
        if self.batch_size < 1 or self.max_steps < 1:
            raise ValueError("batch_size and max_steps must be positive.")
        if self.learning_rate <= 0:
            raise ValueError("learning_rate must be positive.")
        if self.weight_decay < 0 or self.grad_clip <= 0:
            raise ValueError("weight_decay must be non-negative and grad_clip positive.")
        if self.eval_interval < 1 or self.eval_batches < 1:
            raise ValueError("Evaluation settings must be positive.")
        if not 0.0 < self.train_fraction < 1.0:
            raise ValueError("train_fraction must be between 0 and 1.")
        if self.tokenizer_type not in {"character", "bpe"}:
            raise ValueError("tokenizer_type must be character or bpe.")
        if self.tokenizer_vocab_size < 1:
            raise ValueError("tokenizer_vocab_size must be positive.")
        if self.tokenizer_min_frequency < 1:
            raise ValueError("tokenizer_min_frequency must be positive.")
        if self.device not in {"auto", "cpu", "cuda", "mps"}:
            raise ValueError("device must be auto, cpu, cuda, or mps.")


def resolve_device(requested: str = "auto") -> torch.device:
    """Choose an available compute device without requiring a GPU."""
    if requested == "auto":
        if torch.cuda.is_available():
            return torch.device("cuda")
        mps = getattr(torch.backends, "mps", None)
        if mps is not None and mps.is_available():
            return torch.device("mps")
        return torch.device("cpu")

    if requested == "cuda" and not torch.cuda.is_available():
        raise ValueError("CUDA was requested, but no CUDA GPU is available.")

    if requested == "mps":
        mps = getattr(torch.backends, "mps", None)
        if mps is None or not mps.is_available():
            raise ValueError("MPS was requested, but it is not available.")

    return torch.device(requested)


def _make_batch(data: Tensor, batch_size: int, block_size: int,
                device: torch.device) -> tuple[Tensor, Tensor]:
    if data.numel() <= block_size:
        raise ValueError("Each corpus split must contain more tokens than block_size.")

    starts = torch.randint(0, data.numel() - block_size, (batch_size,))
    x = torch.stack([data[i.item():i.item() + block_size] for i in starts])
    y = torch.stack([data[i.item() + 1:i.item() + block_size + 1] for i in starts])
    return x.to(device), y.to(device)


@torch.no_grad()
def _estimate_loss(
    model: TinyTransformerLM,
    data: Tensor,
    config: LanguageModelTrainingConfig,
    device: torch.device,
) -> float:
    model.eval()
    values: list[float] = []

    for _ in range(config.eval_batches):
        x, y = _make_batch(data, config.batch_size, config.block_size, device)
        _, loss = model(x, targets=y)
        if loss is None:
            raise RuntimeError("The model did not return a training loss.")
        values.append(float(loss.item()))

    model.train()
    return sum(values) / len(values)


def train_language_model(
    corpus_path: str | Path,
    output_dir: str | Path,
    config: LanguageModelTrainingConfig | None = None,
    *,
    resume_from: str | Path | None = None,
) -> dict[str, Any]:
    """Train from random initialization or resume a complete saved training state.

    max_steps is the target total step number, not the number of extra steps.
    Full resume requires a checkpoint generated by this resumable implementation,
    with optimizer/RNG state and the same normalized source corpus.
    """
    config = config or LanguageModelTrainingConfig()
    corpus_path = Path(corpus_path)
    output_dir = Path(output_dir)

    if not corpus_path.is_file():
        raise FileNotFoundError(f"Corpus file not found: {corpus_path}")

    text = corpus_path.read_text(encoding="utf-8")
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    if not text.strip():
        raise ValueError("The training corpus cannot be empty or whitespace-only.")

    corpus_sha256 = hashlib.sha256(text.encode("utf-8")).hexdigest()

    # Split raw text before fitting the tokenizer to prevent validation leakage.
    split_at = int(len(text) * config.train_fraction)
    train_text = text[:split_at]
    val_text = text[split_at:]

    if not train_text.strip() or not val_text.strip():
        raise ValueError("Training and validation text splits must both be non-empty.")

    if config.tokenizer_type == "character":
        tokenizer = CharacterTokenizer.fit(train_text)
    else:
        tokenizer = BPETokenizer.fit(
            train_text,
            vocab_size=config.tokenizer_vocab_size,
            min_frequency=config.tokenizer_min_frequency,
        )

    train_data = torch.tensor(tokenizer.encode(train_text), dtype=torch.long)
    val_data = torch.tensor(tokenizer.encode(val_text), dtype=torch.long)

    if train_data.numel() <= config.block_size or val_data.numel() <= config.block_size:
        raise ValueError(
            "Both corpus splits must contain more tokens than block_size. "
            "Increase corpus length or reduce block_size."
        )

    torch.manual_seed(config.seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(config.seed)

    device = resolve_device(config.device)
    model_config = TransformerConfig(
        vocab_size=tokenizer.vocab_size,
        block_size=config.block_size,
        n_layers=config.n_layers,
        n_heads=config.n_heads,
        n_embd=config.n_embd,
        dropout=config.dropout,
    )
    model_config_dict = asdict(model_config)
    model = TinyTransformerLM(model_config).to(device)
    optimizer = torch.optim.AdamW(
        model.parameters(),
        lr=config.learning_rate,
        weight_decay=config.weight_decay,
    )

    output_dir.mkdir(parents=True, exist_ok=True)
    tokenizer.save(output_dir / "tokenizer.json")

    history: list[dict[str, float | int]] = []
    best_val_loss = float("inf")
    start_step = 0

    if resume_from is not None:
        resume_path = Path(resume_from)
        if not resume_path.is_file():
            raise FileNotFoundError(f"Resume checkpoint not found: {resume_path}")

        if resume_path.resolve().parent != output_dir.resolve():
            raise ValueError(
                "For a full resume, use the same output directory as the checkpoint."
            )

        try:
            checkpoint = torch.load(
                resume_path, map_location=device, weights_only=True
            )
        except TypeError:
            checkpoint = torch.load(resume_path, map_location=device)

        if checkpoint.get("format_version") != 1:
            raise ValueError("Unsupported checkpoint format.")
        if checkpoint.get("model_type") != "TinyTransformerLM":
            raise ValueError("Checkpoint does not contain a TinyTransformerLM.")

        required_resume_fields = (
            "optimizer_state_dict",
            "cpu_rng_state",
            "corpus_sha256",
            "metrics_history",
        )
        missing_fields = [
            field for field in required_resume_fields
            if field not in checkpoint
        ]
        if missing_fields:
            raise ValueError(
                "Checkpoint predates full-resume support and lacks: "
                + ", ".join(missing_fields)
                + ". It can be used for a separate weights-only fine-tuning run, "
                  "but not an exact training resume."
            )

        if checkpoint["corpus_sha256"] != corpus_sha256:
            raise ValueError(
                "Resume checkpoint was created from a different corpus."
            )

        if checkpoint["model_config"] != model_config_dict:
            raise ValueError(
                "Model configuration or tokenizer vocabulary differs from checkpoint."
            )

        saved_training_config = checkpoint.get("training_config", {})
        allowed_to_change = {
            "max_steps",
            "device",
            "learning_rate",
            "weight_decay",
            "eval_interval",
            "eval_batches",
            "grad_clip",
        }
        for key, saved_value in saved_training_config.items():
            if key in allowed_to_change:
                continue
            if getattr(config, key, None) != saved_value:
                raise ValueError(
                    f"Training configuration mismatch for {key!r}: "
                    f"checkpoint={saved_value!r}, requested={getattr(config, key, None)!r}."
                )

        start_step = int(checkpoint["step"])
        if config.max_steps <= start_step:
            raise ValueError(
                f"max_steps ({config.max_steps}) must exceed the resumed step "
                f"({start_step})."
            )

        model.load_state_dict(checkpoint["model_state_dict"])
        optimizer.load_state_dict(checkpoint["optimizer_state_dict"])

        # Let the explicitly requested continuation LR/weight decay take effect.
        for parameter_group in optimizer.param_groups:
            parameter_group["lr"] = config.learning_rate
            parameter_group["weight_decay"] = config.weight_decay

        history = list(checkpoint["metrics_history"])
        best_val_loss = float(
            checkpoint.get("best_val_loss", checkpoint.get("val_loss", float("inf")))
        )

        # Restore RNG state after model and optimizer initialization.
        torch.set_rng_state(checkpoint["cpu_rng_state"].cpu())
        if device.type == "cuda" and checkpoint.get("cuda_rng_states"):
            torch.cuda.set_rng_state_all(
                [state.cpu() for state in checkpoint["cuda_rng_states"]]
            )

        print(
            f"Resuming from step {start_step}; "
            f"continuing toward total step {config.max_steps} on {device}."
        )

    tokenizer.save(output_dir / "tokenizer.json")
    final_train_loss = float("nan")
    final_val_loss = float("nan")

    for step in range(start_step + 1, config.max_steps + 1):
        model.train()
        x, y = _make_batch(
            train_data, config.batch_size, config.block_size, device
        )
        optimizer.zero_grad(set_to_none=True)
        _, loss = model(x, targets=y)

        if loss is None or not torch.isfinite(loss):
            raise RuntimeError(f"Invalid training loss at step {step}.")

        loss.backward()
        torch.nn.utils.clip_grad_norm_(model.parameters(), config.grad_clip)
        optimizer.step()

        if step % config.eval_interval == 0 or step == config.max_steps:
            final_train_loss = _estimate_loss(model, train_data, config, device)
            final_val_loss = _estimate_loss(model, val_data, config, device)

            record: dict[str, float | int] = {
                "step": step,
                "train_loss": final_train_loss,
                "val_loss": final_val_loss,
            }
            history.append(record)

            is_best = final_val_loss < best_val_loss
            if is_best:
                best_val_loss = final_val_loss

            checkpoint = {
                "format_version": 1,
                "model_type": "TinyTransformerLM",
                "step": step,
                "model_config": model_config_dict,
                "training_config": asdict(config),
                "model_state_dict": model.state_dict(),
                "optimizer_state_dict": optimizer.state_dict(),
                "cpu_rng_state": torch.get_rng_state(),
                "cuda_rng_states": (
                    [state.cpu() for state in torch.cuda.get_rng_state_all()]
                    if torch.cuda.is_available() else []
                ),
                "corpus_sha256": corpus_sha256,
                "metrics_history": history.copy(),
                "best_val_loss": best_val_loss,
                "train_loss": final_train_loss,
                "val_loss": final_val_loss,
            }

            torch.save(checkpoint, output_dir / "last.pt")
            if is_best:
                torch.save(checkpoint, output_dir / "best.pt")

            (output_dir / "metrics.json").write_text(
                json.dumps(history, indent=2) + "\n",
                encoding="utf-8",
            )

            print(
                f"step {step}/{config.max_steps} | "
                f"train_loss={final_train_loss:.4f} | "
                f"val_loss={final_val_loss:.4f} | device={device}"
            )

    return {
        "output_dir": str(output_dir),
        "best_checkpoint": str(output_dir / "best.pt"),
        "last_checkpoint": str(output_dir / "last.pt"),
        "tokenizer_path": str(output_dir / "tokenizer.json"),
        "steps": config.max_steps,
        "best_val_loss": best_val_loss,
        "final_train_loss": final_train_loss,
        "final_val_loss": final_val_loss,
        "device": str(device),
        "resumed_from_step": start_step,
        "corpus_sha256": corpus_sha256,
    }


def load_language_model(
    checkpoint_path: str | Path,
    device: str = "auto",
) -> tuple[TinyTransformerLM, CharacterTokenizer, dict[str, Any]]:
    """Load a checkpoint produced by train_language_model."""
    checkpoint_path = Path(checkpoint_path)
    if not checkpoint_path.is_file():
        raise FileNotFoundError(f"Checkpoint not found: {checkpoint_path}")

    target_device = resolve_device(device)
    try:
        checkpoint = torch.load(
            checkpoint_path, map_location=target_device, weights_only=True
        )
    except TypeError:
        # Compatibility with older PyTorch versions; only load trusted local files.
        checkpoint = torch.load(checkpoint_path, map_location=target_device)

    if checkpoint.get("format_version") != 1:
        raise ValueError("Unsupported checkpoint format.")
    if checkpoint.get("model_type") != "TinyTransformerLM":
        raise ValueError("Checkpoint does not contain a TinyTransformerLM.")

    model_config = TransformerConfig(**checkpoint["model_config"])
    tokenizer_path = checkpoint_path.parent / "tokenizer.json"
    tokenizer_metadata = json.loads(
        tokenizer_path.read_text(encoding="utf-8")
    )
    tokenizer_kind = tokenizer_metadata.get("tokenizer_type")
    if tokenizer_kind == "character":
        tokenizer = CharacterTokenizer.load(tokenizer_path)
    elif tokenizer_kind == "bpe_char":
        tokenizer = BPETokenizer.load(tokenizer_path)
    else:
        raise ValueError(
            f"Unsupported tokenizer type in checkpoint: {tokenizer_kind!r}"
        )

    if tokenizer.vocab_size != model_config.vocab_size:
        raise ValueError("Checkpoint and tokenizer vocabulary sizes do not match.")

    model = TinyTransformerLM(model_config).to(target_device)
    model.load_state_dict(checkpoint["model_state_dict"])
    model.eval()
    return model, tokenizer, checkpoint


@torch.no_grad()
def generate_text(
    checkpoint_path: str | Path,
    prompt: str,
    max_new_tokens: int = 100,
    temperature: float = 1.0,
    top_k: int | None = None,
    device: str = "auto",
) -> str:
    """Generate text from a trained checkpoint, without an external AI API."""
    if not prompt:
        raise ValueError("Prompt cannot be empty.")
    if max_new_tokens < 0:
        raise ValueError("max_new_tokens cannot be negative.")

    model, tokenizer, _ = load_language_model(checkpoint_path, device=device)
    target_device = next(model.parameters()).device
    input_ids = torch.tensor(
        [tokenizer.encode(prompt)], dtype=torch.long, device=target_device
    )
    generated = model.generate(
        input_ids,
        max_new_tokens=max_new_tokens,
        temperature=temperature,
        top_k=top_k,
    )
    return tokenizer.decode(generated[0].tolist())
